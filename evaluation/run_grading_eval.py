"""Auto-grading benchmark: agreement between the agent's grades and human grades.

Input: evaluation/data/grading_set.jsonl, one line per (question, student answer):
  {"id": "g001", "question": "...", "concept": "reponse_specifique",
   "rubric": [{"criterion": "...", "points": 1}], "reference": "official corrigé ...",
   "student_answer": "...", "human_score": 1.5, "max_score": 2}

How to build it (see docs/EVALUATION.md):
  1. take 15-20 questions from bac sujets with their official corrigé + barème;
  2. write 3-4 answers per question of different quality (excellent / partial / misconception / off-topic),
     or collect real answers from bac students;
  3. grade them yourself with the official barème -> human_score.

Ablation: with the official rubric vs. a rubric generated by the agent (--generated-rubric).

    python evaluation/run_grading_eval.py
"""
from __future__ import annotations

import argparse

from common import DATA, load_jsonl, markdown_table, save_results
from metrics import grading_agreement

from app.services import get_agent


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--file", default=str(DATA / "grading_set.jsonl"))
    ap.add_argument("--generated-rubric", action="store_true", help="ignore official rubric (ablation)")
    args = ap.parse_args()

    from pathlib import Path
    rows = load_jsonl(Path(args.file))
    agent = get_agent()
    preds, details = [], []
    for r in rows:
        out = agent.grade(f"eval-grader", r["question"], r["student_answer"],
                          rubric=None if args.generated_rubric else r.get("rubric"),
                          reference=r.get("reference"), concept=r.get("concept"), max_points=r["max_score"])
        g = out["grade"]
        # the generated rubric may not sum to max_score: rescale
        score = g["score"] * r["max_score"] / g["max_score"] if g["max_score"] else 0.0
        preds.append(score)
        details.append({"id": r["id"], "human": r["human_score"], "model": round(score, 2),
                        "max": r["max_score"], "feedback": g["feedback"]})
        print(f"{r['id']}: human={r['human_score']} model={score:.2f}/{r['max_score']}")

    res = grading_agreement(preds, [r["human_score"] for r in rows], [r["max_score"] for r in rows])
    res["rubric"] = "generated" if args.generated_rubric else "official"
    print("\n" + markdown_table([res], ["rubric", "n", "mae_points", "within_0.5pt", "pearson", "qwk", "bias_points"]))
    save_results(f"grading_{res['rubric']}", {"summary": res, "details": details})


if __name__ == "__main__":
    main()
